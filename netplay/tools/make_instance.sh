#!/bin/bash
# Creates (or refreshes) a test instance directory to use as the game's user_data_root.
#
#   make_instance.sh <name> <gamertag> [--force-relay] [--privacy] [--no-lan]
#
# <run>/instances/<name>/ gets:
#   ac6recomp.toml   windowed 960x540 config with the [netplay] section (dev server and key)
#   launch.sh        starts the game for this instance (see launch_instance.sh)
#   B13EBABEBABEBABE/ 0000000000000000/ dlc/   copies of Cole's save data, cloned once
#   cache/shaders/   copy of the shader cache (faster startup)
#   shots/           screenshot trigger directory (touch shots/capture.now)
# The save source (AC6NP_SAVE_SRC, default ~/.local/share/ac6recomp) is only ever read.
# Re-running rewrites ac6recomp.toml and launch.sh and keeps the instance's saves; delete the
# instance directory to clone fresh saves. The dev server must have run once (for its key).
set -euo pipefail

# shellcheck source=common.sh
. "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/common.sh"

usage() {
  sed -n '2,16p' "$0" >&2
  exit 2
}

[ "$#" -ge 2 ] || usage
name="$1"
gamertag="$2"
shift 2
force_relay=false
privacy=false
lan=true
while [ "$#" -gt 0 ]; do
  case "$1" in
    --force-relay) force_relay=true ;;
    --privacy) privacy=true ;;
    --no-lan) lan=false ;;
    -h | --help) usage ;;
    *) die "unknown option '$1'" ;;
  esac
  shift
done

valid_instance_name "$name" || die "instance name must be 1-32 characters of A-Z a-z 0-9 _ -"
case "$gamertag" in
  "" | *[!A-Za-z0-9\ ]*) die "gamertag must be letters, digits and spaces" ;;
esac
[ "${#gamertag}" -le 15 ] || die "gamertag must be at most 15 characters"

key="$(server_pubkey)" ||
  die "no server key in $AC6NP_SERVER_DATA; run dev_server.sh once first"

dir="$(instance_dir "$name")"
if pid="$(pid_from_file "$dir/ac6recomp.pid" ac6recomp)"; then
  die "instance $name is running (PID $pid); stop it first (stop_instance.sh $name)"
fi
mkdir -p "$dir" "$dir/shots"
dir="$(cd "$dir" && pwd -P)"

# Refuse to write anywhere inside the save source: it must stay untouched.
if [ -d "$AC6NP_SAVE_SRC" ]; then
  save_src_real="$(cd "$AC6NP_SAVE_SRC" && pwd -P)"
  case "$dir/" in
    "$save_src_real"/*) die "instance dir $dir is inside the save source $save_src_real" ;;
  esac
fi

# Copy-on-write clones on APFS (cp -c), plain copies elsewhere. Reads the source only.
clone_tree() {
  local src="$1" dst="$2"
  if [ "$(uname -s)" = Darwin ] && cp -Rpc "$src" "$dst" 2> /dev/null; then
    return 0
  fi
  rm -rf "$dst"
  cp -Rp "$src" "$dst"
}

if [ ! -f "$dir/.saves_cloned" ]; then
  [ -d "$AC6NP_SAVE_SRC" ] || die "save source $AC6NP_SAVE_SRC does not exist"
  for item in B13EBABEBABEBABE 0000000000000000 dlc; do
    if [ -d "$AC6NP_SAVE_SRC/$item" ]; then
      [ ! -e "$dir/$item" ] || die "$dir/$item exists but .saves_cloned is missing; delete the instance dir and retry"
      note "cloning $item"
      clone_tree "$AC6NP_SAVE_SRC/$item" "$dir/$item"
    else
      note "warning: $AC6NP_SAVE_SRC/$item not found; skipped"
    fi
  done
  if [ -d "$AC6NP_SAVE_SRC/cache/shaders" ] && [ ! -e "$dir/cache/shaders" ]; then
    note "cloning cache/shaders"
    mkdir -p "$dir/cache"
    clone_tree "$AC6NP_SAVE_SRC/cache/shaders" "$dir/cache/shaders"
  fi
  printf 'cloned from %s at %s\n' "$AC6NP_SAVE_SRC" "$(date '+%Y-%m-%d %H:%M:%S %z')" > "$dir/.saves_cloned"
else
  note "keeping existing saves in $dir (delete the directory to clone fresh ones)"
fi

cat > "$dir/ac6recomp.toml" << EOF
# Generated by netplay/tools/make_instance.sh for instance "$name"; re-running it rewrites
# this file. Display and GPU tuning flags are passed by launch_instance.sh.
fullscreen = false
window_width = 960
window_height = 540

[netplay]
enabled = true
server = $(toml_string "$AC6NP_SERVER_UDP")
server_key = $(toml_string "$key")
gamertag = $(toml_string "$gamertag")
port = 0
force_relay = $force_relay
privacy = $privacy
lan = $lan
trace = $(toml_string "$dir/trace.jsonl")
input_script = ""
dump_spa = ""
screenshot_dir = $(toml_string "$dir/shots")

[log.levels]
netinput = "info"
EOF

{
  printf '#!/bin/bash\n'
  printf '# Generated by netplay/tools/make_instance.sh: starts instance "%s" (%s).\n' "$name" "$gamertag"
  printf '# Usage: launch.sh [--input-script FILE] [--dry-run] [-- extra game flags]\n'
  # shellcheck disable=SC2016  # "$@" is meant literally: it belongs to the generated script
  printf 'exec %q %q "$@"\n' "$AC6NP_TOOLS_DIR/launch_instance.sh" "$dir"
} > "$dir/launch.sh"
chmod +x "$dir/launch.sh"

note "instance $name ($gamertag) ready: $dir"
note "  server $AC6NP_SERVER_UDP, force_relay=$force_relay privacy=$privacy lan=$lan"
note "  start: $dir/launch.sh   trace: $dir/trace.jsonl   screenshots: touch $dir/shots/capture.now"
